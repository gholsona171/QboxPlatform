/** Validates and brands a Discord user snowflake. */
export function discordUserId(value: string): DiscordUserId {
  return discordSnowflake(value, "Discord user") as DiscordUserId;
}

/** Validates and brands a Discord guild snowflake. */
export function discordGuildId(value: string): DiscordGuildId {
  return discordSnowflake(value, "Discord guild") as DiscordGuildId;
}

