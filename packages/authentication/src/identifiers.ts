export function discordRoleId(value: string): DiscordRoleId {
  return discordSnowflake(value, "Discord role") as DiscordRoleId;
}

/** Validates a lowercase 32-byte keyed-HMAC digest for safe persistence. */
export function authenticationDigest(value: string): AuthenticationDigest {
  if (!DIGEST_PATTERN.test(value))
    throw new AuthenticationDomainError(
      "invalid-identifier",
      "Authentication digests must be 64 lowercase hexadecimal characters.",
    );
  return value as AuthenticationDigest;
}

/** Brands an in-memory opaque secret after rejecting empty or control-filled values. */
export function opaqueAuthenticationSecret(
  value: string,
): OpaqueAuthenticationSecret {
  if (value.length < 32 || value.length > 4096 || /[\u0000-\u001f\u007f]/.test(value))
    throw new AuthenticationDomainError(
      "invalid-identifier",
      "Opaque authentication secrets must have a safe bounded representation.",
    );
  return value as OpaqueAuthenticationSecret;
}

function canonicalUuid(value: string, label: string): string {
  if (!UUID_PATTERN.test(value))
    throw new AuthenticationDomainError(
      "invalid-identifier",
      `${label} identifiers must be canonical lowercase UUIDs.`,
    );
  return value;
}

function discordSnowflake(value: string, label: string): string {
  if (!DISCORD_SNOWFLAKE_PATTERN.test(value))
    throw new AuthenticationDomainError(
      "invalid-identifier",
      `${label} identifiers must be 17 to 20 digit Discord snowflakes.`,
    );
  return value;
}
